package museon_online.astor_butler.fsm.core;

public enum BotState {
    UNKNOWN,
    CONSENT_REQUIRED,
    READY_FOR_DIALOG,
    AI_FALLBACK,
    MENU_ASSETS_CLARIFY,
    MENU_ASSETS_DELIVERED,
    QUIET_GUIDE_CLARIFY,
    QUIET_GUIDE_DELIVERED,
    TABLE_BOOKING_INTENT,
    TABLE_BOOKING_COLLECT_DATE,
    TABLE_BOOKING_COLLECT_TIME,
    TABLE_BOOKING_COLLECT_PARTY_SIZE,
    TABLE_BOOKING_COLLECT_SEATING_PREFERENCE,
    TABLE_BOOKING_SHOW_PLAN,
    TABLE_BOOKING_WAIT_TABLE_SELECTION,
    TABLE_BOOKING_WAIT_HOSTESS_CONFIRMATION,
    TABLE_BOOKING_CONFIRMED,
    TABLE_BOOKING_REJECTED,
    TABLE_BOOKING_CHANGE_REQUESTED,
    TABLE_BOOKING_CANCELLED,
    BUSINESS_LUNCH_CHOOSE_SET,
    BUSINESS_LUNCH_CHOOSE_DISH,
    BUSINESS_LUNCH_COLLECT_PARTY_SIZE,
    BUSINESS_LUNCH_COLLECT_DATE,
    BUSINESS_LUNCH_COLLECT_TIME,
    BUSINESS_LUNCH_CONFIRMATION,
    EVENT_BOOKING_COLLECT_DETAILS,
    EVENT_BOOKING_SENT,
    TIP_COLLECT_AMOUNT,
    TIP_CONFIRMATION,
    DONATION_COLLECT_AMOUNT,
    DONATION_CONFIRMATION,
    AUCTION_RUNNING,
    AUCTION_WAIT_BID,
    MANAGER_HELP_COLLECT_REASON,
    MANAGER_HELP_SENT,
    FEEDBACK_COLLECT_TEXT,
    FEEDBACK_SENT,
    PREFERENCE_COLLECT_TEXT,
    PREFERENCE_SAVED,
    CONCIERGE_COLLECT_REQUEST,
    CONCIERGE_SENT,
    MERCH_COLLECT_REQUEST,
    MERCH_SENT,
    SAFE_PLAY_COLLECT_DETAILS,
    SAFE_PLAY_WAIT_TEAM_CONFIRMATION,
    SAFE_EXIT,

    @Deprecated(forRemoval = false)
    GREETING,

    @Deprecated(forRemoval = false)
    CONTACT,

    @Deprecated(forRemoval = false)
    MENU;

    public BotState canonical() {
        return switch (this) {
            case GREETING, CONTACT -> CONSENT_REQUIRED;
            case MENU -> READY_FOR_DIALOG;
            default -> this;
        };
    }

    public boolean waitsForConsentAndContact() {
        return canonical() == CONSENT_REQUIRED;
    }

    public static BotState fromStorageValue(String value) {
        if (value == null || value.isBlank()) {
            return null;
        }
        return BotState.valueOf(value).canonical();
    }
}
