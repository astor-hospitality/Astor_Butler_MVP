-- How a guest came in (#128): a staff member showed a personal link or QR from a phone, or the guest scanned the
-- printed QR at the host stand (pseudo staff id "host"). One row per /start with such a parameter, written before
-- the dialogue answers. No names or phones here: the row points at the chat and at staff_id in astor_staff_members.
-- No foreign key on purpose: an unknown or retired staff id must never fail the guest's entry.

CREATE TABLE IF NOT EXISTS guest_entry_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant VARCHAR(80),
    chat_id BIGINT NOT NULL,
    staff_id VARCHAR(128) NOT NULL,
    table_code VARCHAR(32),
    source VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_guest_entry_events_chat
    ON guest_entry_events(chat_id, created_at DESC);
