-- The shift schedule from a photo the staff posts to the «График» topic (docs/operations/STAFF_SHIFT_SCHEDULE.md).
-- A schedule is one recognised picture; its rows are a day, the name as written, the role and the hours. Only the
-- minimum is kept: no phones, no picture, no raw model answer. A row gets a staff_id once the name is matched to
-- the directory (astor_staff_members) without doubt or a person picked it with a button.
-- The latest CONFIRMED schedule covering a day answers «who is on shift» for that day.

CREATE TABLE IF NOT EXISTS staff_shift_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant VARCHAR(80) NOT NULL,
    chat_id BIGINT NOT NULL,
    message_id INTEGER NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('CLARIFYING', 'PROPOSED', 'CONFIRMED', 'REJECTED')),
    first_date DATE NOT NULL,
    last_date DATE NOT NULL,
    unreadable INTEGER NOT NULL DEFAULT 0,
    posted_by VARCHAR(160),
    model VARCHAR(120),
    reply_message_id INTEGER,
    decided_by VARCHAR(160),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (tenant, chat_id, message_id)
);

CREATE INDEX IF NOT EXISTS idx_staff_shift_schedules_confirmed
    ON staff_shift_schedules(tenant, status, first_date, last_date);

CREATE TABLE IF NOT EXISTS staff_shift_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL REFERENCES staff_shift_schedules(id) ON DELETE CASCADE,
    shift_date DATE NOT NULL,
    raw_name VARCHAR(60) NOT NULL,
    -- Null when the picture gave no role and the name is not settled yet; the directory's role fills it then.
    role VARCHAR(16) CHECK (role IS NULL OR role IN ('WAITER', 'HOSTESS', 'MANAGER')),
    starts_at TIME,
    ends_at TIME,
    match_status VARCHAR(16) NOT NULL CHECK (match_status IN ('MATCHED', 'AMBIGUOUS', 'UNKNOWN', 'DISMISSED')),
    staff_id VARCHAR(128),
    candidates VARCHAR(400)
);

CREATE INDEX IF NOT EXISTS idx_staff_shift_entries_day
    ON staff_shift_entries(schedule_id, shift_date);

-- A name form a person resolved with a button («Аня» → anna): next time it matches without a question.
CREATE TABLE IF NOT EXISTS staff_name_aliases (
    tenant VARCHAR(80) NOT NULL,
    alias VARCHAR(60) NOT NULL,
    staff_id VARCHAR(128) NOT NULL,
    created_by VARCHAR(160),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tenant, alias),
    FOREIGN KEY (tenant, staff_id) REFERENCES astor_staff_members(tenant, staff_id) ON DELETE CASCADE
);
