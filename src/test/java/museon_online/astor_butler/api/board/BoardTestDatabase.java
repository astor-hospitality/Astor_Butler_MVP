package museon_online.astor_butler.api.board;

import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.UUID;

/**
 * The board reads seven schemas: the journey, ledger, summary and billing ones run from their real migrations; reservations and the
 * model audit are reduced to the columns the board reads (their migrations use PostgreSQL-only SQL).
 */
final class BoardTestDatabase implements AutoCloseable {

    private static final String REDUCED = """
            CREATE TABLE venue_tables (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, table_code VARCHAR(32) NOT NULL,
                display_name VARCHAR(120) NOT NULL);
            CREATE TABLE table_reservation_orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, table_id BIGINT,
                guest_name VARCHAR(160), guest_phone VARCHAR(80), chat_id BIGINT, telegram_user_id BIGINT,
                status VARCHAR(40) NOT NULL DEFAULT 'DRAFT', source VARCHAR(40) NOT NULL DEFAULT 'TELEGRAM', party_size INTEGER,
                requested_start_at TIMESTAMP WITH TIME ZONE,
                created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
            CREATE TABLE model_interaction_audit (interaction_id UUID PRIMARY KEY, prompt TEXT NOT NULL,
                fallback_used BOOLEAN NOT NULL DEFAULT FALSE, success BOOLEAN NOT NULL DEFAULT TRUE, latency_ms BIGINT,
                created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
            """;

    private final Connection schema;
    private final JdbcTemplate jdbc;

    private BoardTestDatabase(Connection schema, JdbcTemplate jdbc) {
        this.schema = schema;
        this.jdbc = jdbc;
    }

    static BoardTestDatabase create() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:board-" + UUID.randomUUID() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
        try {
            Connection schema = dataSource.getConnection();
            ScriptUtils.executeSqlScript(schema, new ClassPathResource("db/changelog/2026-10-14-guest-journey.sql"));
            ScriptUtils.executeSqlScript(schema, new ClassPathResource("db/changelog/2026-10-15-visit-turns.sql"));
            ScriptUtils.executeSqlScript(schema, new ClassPathResource("db/changelog/2026-10-15-visit-summaries.sql"));
            ScriptUtils.executeSqlScript(schema, new ClassPathResource("db/changelog/2026-10-07-guest-billing.sql"));
            ScriptUtils.executeSqlScript(schema, new ClassPathResource("db/changelog/2026-10-08-guest-billing-payment-review.sql"));
            ScriptUtils.executeSqlScript(schema, new ByteArrayResource(REDUCED.getBytes(StandardCharsets.UTF_8)));
            return new BoardTestDatabase(schema, new JdbcTemplate(dataSource));
        } catch (SQLException e) {
            throw new IllegalStateException("Cannot build the board test database", e);
        }
    }

    JdbcTemplate jdbc() {
        return jdbc;
    }

    long reservation(String guestName, String phone, String tableName, Instant createdAt) {
        Long tableId = null;
        if (tableName != null) {
            jdbc.update("INSERT INTO venue_tables(table_code, display_name) VALUES (?, ?)", tableName, tableName);
            tableId = jdbc.queryForObject("SELECT max(id) FROM venue_tables", Long.class);
        }
        jdbc.update("INSERT INTO table_reservation_orders(table_id, guest_name, guest_phone, created_at, updated_at) VALUES (?, ?, ?, ?, ?)",
                tableId, guestName, phone, Timestamp.from(createdAt), Timestamp.from(createdAt));
        return jdbc.queryForObject("SELECT max(id) FROM table_reservation_orders", Long.class);
    }

    long visit(long reservationId, String phone, String stage, Instant visitDay, int guestMessages) {
        jdbc.update("INSERT INTO guest_visits(reservation_id, guest_phone, venue_code, stage, visit_day, guest_messages) "
                + "VALUES (?, ?, 'AERIS', ?, ?, ?)", reservationId, phone, stage, Timestamp.from(visitDay), guestMessages);
        return jdbc.queryForObject("SELECT id FROM guest_visits WHERE reservation_id = ?", Long.class, reservationId);
    }

    /** A reservation as the manager's day reads it: status, channel, party, time and the guest's Telegram ids. */
    long booking(String guestName, String status, String source, Integer partySize, Long telegramUserId, Long chatId,
                 Instant startAt, Instant createdAt, String tableName) {
        long id = reservation(guestName, null, tableName, createdAt);
        jdbc.update("UPDATE table_reservation_orders SET status = ?, source = ?, party_size = ?, telegram_user_id = ?, chat_id = ?, "
                + "requested_start_at = ? WHERE id = ?", status, source, partySize, telegramUserId, chatId,
                startAt == null ? null : Timestamp.from(startAt), id);
        return id;
    }

    long visit(long reservationId, String venue, String stage, Long chatId, Instant openedAt) {
        jdbc.update("INSERT INTO guest_visits(reservation_id, chat_id, venue_code, stage, opened_at) VALUES (?, ?, ?, ?, ?)",
                reservationId, chatId, venue, stage, Timestamp.from(openedAt));
        return jdbc.queryForObject("SELECT id FROM guest_visits WHERE reservation_id = ?", Long.class, reservationId);
    }

    long lunchBill(long reservationId, Long estimateMinor, Long venueAmountMinor) {
        jdbc.update("INSERT INTO guest_bills(chat_id, kind, table_reservation_id, estimate_minor, venue_amount_minor) "
                + "VALUES (1, 'BUSINESS_LUNCH', ?, ?, ?)", reservationId, estimateMinor, venueAmountMinor);
        return jdbc.queryForObject("SELECT id FROM guest_bills WHERE table_reservation_id = ?", Long.class, reservationId);
    }

    void review(long billId, Integer stars) {
        jdbc.update("INSERT INTO visit_reviews(bill_id, chat_id, stars) VALUES (?, 1, ?)", billId, stars);
    }

    void sessionTurn(long visitId, String sessionId, Instant at) {
        jdbc.update("INSERT INTO visit_turns(visit_id, session_id, at, side, channel, kind, text) "
                + "VALUES (?, ?, ?, 'CONCIERGE', 'CONCIERGE_TG', 'MESSAGE', 'x')", visitId, sessionId, Timestamp.from(at));
    }

    void turn(Long visitId, String side, String kind, String text, String payload, Instant at) {
        jdbc.update("INSERT INTO visit_turns(visit_id, at, side, channel, kind, text, payload) VALUES (?, ?, ?, 'INTERNAL', ?, ?, ?)",
                visitId, Timestamp.from(at), side, kind, text, payload);
    }

    void event(long visitId, String kind, Instant at) {
        jdbc.update("INSERT INTO guest_visit_events(visit_id, kind, axis, source, occurred_at) VALUES (?, ?, 'TIME', 'BOT', ?)",
                visitId, kind, Timestamp.from(at));
    }

    void modelCall(boolean success, boolean fallback, long latencyMs, Instant at) {
        jdbc.update("INSERT INTO model_interaction_audit(interaction_id, prompt, success, fallback_used, latency_ms, created_at) "
                + "VALUES (?, 'p', ?, ?, ?, ?)", UUID.randomUUID(), success, fallback, latencyMs, Timestamp.from(at));
    }

    void sabyCall(int status, String outcome, Instant at) {
        jdbc.update("INSERT INTO saby_call_log(http_method, operation, http_status, outcome, duration_ms, occurred_at) "
                + "VALUES ('GET', '/x', ?, ?, 10, ?)", status, outcome, Timestamp.from(at));
    }

    @Override
    public void close() throws SQLException {
        try (Connection connection = schema; Statement statement = connection.createStatement()) {
            statement.execute("SHUTDOWN");
        }
    }
}
