package museon_online.astor_butler.domain.booking;

import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.UUID;

/**
 * A fresh in-memory database with the three booking tables as the production migrations define them
 * (2026-06-05-table-booking-foundation.sql, 2026-06-16-table-booking-seating-preferences.sql), minus what H2 cannot
 * run from those files: the foreign keys to {@code users}, the partial index and the seed upsert. The later migrations
 * that only add columns (2026-10-12-booking-seated.sql, #151) are applied as they are. The repository SQL then runs
 * unchanged, so the tests exercise the real queries behind the hold, its expiry and the seating.
 */
final class TableReservationTestDatabase {

    private TableReservationTestDatabase() {
    }

    static JdbcTemplate create() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:table-booking-" + UUID.randomUUID() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE venue_tables (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    venue_code VARCHAR(64) NOT NULL DEFAULT 'AERIS',
                    table_code VARCHAR(32) NOT NULL,
                    display_name VARCHAR(120) NOT NULL,
                    zone VARCHAR(40) NOT NULL,
                    capacity_min INTEGER NOT NULL DEFAULT 1,
                    capacity_max INTEGER NOT NULL,
                    combinable_group VARCHAR(64),
                    bookable BOOLEAN NOT NULL DEFAULT TRUE,
                    active BOOLEAN NOT NULL DEFAULT TRUE,
                    plan_page INTEGER NOT NULL DEFAULT 2,
                    plan_ref VARCHAR(255),
                    sort_order INTEGER NOT NULL DEFAULT 0,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT uq_venue_tables_code UNIQUE (venue_code, table_code)
                )
                """);
        jdbc.execute("""
                CREATE TABLE table_reservation_orders (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    chat_id BIGINT,
                    telegram_user_id BIGINT,
                    user_id BIGINT,
                    table_id BIGINT,
                    status VARCHAR(40) NOT NULL DEFAULT 'DRAFT',
                    source VARCHAR(40) NOT NULL DEFAULT 'TELEGRAM',
                    requested_start_at TIMESTAMP WITH TIME ZONE,
                    requested_end_at TIMESTAMP WITH TIME ZONE,
                    party_size INTEGER,
                    guest_name VARCHAR(160),
                    guest_phone VARCHAR(80),
                    guest_comment VARCHAR(4000),
                    preferred_zone VARCHAR(40),
                    seating_preference VARCHAR(4000),
                    manager_telegram_id BIGINT NOT NULL DEFAULT 876857557,
                    manager_user_id BIGINT,
                    hostess_chat_id VARCHAR(120),
                    sbis_external_id VARCHAR(120),
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE table_reservation_holds (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    table_id BIGINT NOT NULL,
                    order_id BIGINT NOT NULL,
                    status VARCHAR(40) NOT NULL DEFAULT 'HELD',
                    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
                    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
                    expires_at TIMESTAMP WITH TIME ZONE,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        try (Connection connection = dataSource.getConnection()) {
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/changelog/2026-10-12-booking-seated.sql"));
        } catch (SQLException e) {
            throw new IllegalStateException("Cannot apply the seating migration to the test database", e);
        }
        return jdbc;
    }

    static void table(JdbcTemplate jdbc, long id, String code, String zone, int capacityMax) {
        jdbc.update("""
                INSERT INTO venue_tables (id, venue_code, table_code, display_name, zone, capacity_min, capacity_max, sort_order)
                VALUES (?, 'AERIS', ?, ?, ?, 1, ?, ?)
                """, id, code, "Table " + code, zone, capacityMax, id);
    }

    /** An order as the dialogue stores it; {@code updatedAt} is when the hostess card was sent. */
    static void order(JdbcTemplate jdbc, long id, long chatId, long tableId, TableReservationStatus status,
                      Instant startAt, Instant endAt, String externalId, Instant updatedAt) {
        jdbc.update("""
                INSERT INTO table_reservation_orders (
                    id, chat_id, telegram_user_id, table_id, status, source, requested_start_at, requested_end_at,
                    party_size, guest_name, guest_phone, hostess_chat_id, sbis_external_id, created_at, updated_at
                )
                VALUES (?, ?, ?, ?, ?, 'TELEGRAM', ?, ?, 2, 'Ирина', '+79990000000', '500', ?, ?, ?)
                """, id, chatId, chatId, tableId, status.name(), Timestamp.from(startAt), Timestamp.from(endAt),
                externalId, Timestamp.from(updatedAt), Timestamp.from(updatedAt));
    }

    /** The hold as {@code createHold} writes it: {@code expires_at} is the visit start plus 15 minutes. */
    static void hold(JdbcTemplate jdbc, long orderId, long tableId, String status, Instant startAt, Instant endAt) {
        jdbc.update("""
                INSERT INTO table_reservation_holds (table_id, order_id, status, start_at, end_at, expires_at)
                VALUES (?, ?, ?, ?, ?, ?)
                """, tableId, orderId, status, Timestamp.from(startAt), Timestamp.from(endAt),
                Timestamp.from(startAt.plusSeconds(15 * 60L)));
    }

    /** The guest sat down at {@code at}, as {@code seatIfConfirmed} leaves the row but with a chosen time. */
    static void seated(JdbcTemplate jdbc, long orderId, Instant at) {
        jdbc.update("UPDATE table_reservation_orders SET status = 'SEATED', seated_at = ? WHERE id = ?",
                Timestamp.from(at), orderId);
    }

    static String holdStatus(JdbcTemplate jdbc, long orderId) {
        return jdbc.queryForObject(
                "SELECT status FROM table_reservation_holds WHERE order_id = ? ORDER BY id DESC LIMIT 1", String.class, orderId);
    }

    static int holds(JdbcTemplate jdbc, long orderId) {
        Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM table_reservation_holds WHERE order_id = ?", Integer.class, orderId);
        return count == null ? 0 : count;
    }
}
