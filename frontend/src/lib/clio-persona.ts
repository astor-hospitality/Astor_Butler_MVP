export function clioDemoReply(text: string, step: number): string {
  const normalized = text.toLowerCase();
  if (normalized.includes("свад")) {
    return "Для свадебного фильма важно сохранить историю дня, а не просто кадры. Подскажите дату, город, длительность съемки и нужен ли Love Story до свадьбы.";
  }
  if (normalized.includes("реклам") || normalized.includes("бренд")) {
    return "Для рекламы начнем с цели ролика, аудитории, продукта и площадок размещения. Затем можно собрать сценарную основу и оценить масштаб продакшна.";
  }
  if (normalized.includes("срок") || normalized.includes("когда") || normalized.includes("тайм")) {
    return "По срокам честно: они зависят от формата, смен, монтажа и согласований. Подскажите продукт и желаемый период, я соберу вводные для команды.";
  }
  if (normalized.includes("продюсер") || normalized.includes("менеджер") || normalized.includes("созвон")) {
    return "Передам запрос продюсеру после короткого брифа. Напишите, пожалуйста, продукт, цель, дату или период и удобный контакт.";
  }
  if (normalized.includes("бриф") || normalized.includes("смет")) {
    return "Я соберу короткий бриф: формат, цель, период, площадки публикации, референсы, бюджетная вилка и контакт для связи.";
  }
  if (step <= 0) return FOLLOW_UP_QUESTIONS[0];
  if (step <= FOLLOW_UP_QUESTIONS.length) return FOLLOW_UP_QUESTIONS[step - 1];
  return "Спасибо. Я собрала вводные в заявку. Команда сможет продолжить с конкретикой по формату, срокам и смете.";
}
