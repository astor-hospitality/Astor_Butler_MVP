/**
 * The pages of the directions: packages, prices, what is included, how it goes, timing and terms.
 *
 * The Russian facts are taken as they stand from the current site (c3ag.ru, `frontend/lib/products.ts`), which was
 * transcribed from the studio's commercial proposals: a page must never contradict a proposal already in a client's inbox.
 * So prices, package names and the lists are not to be reworded here; change them only together with the proposals.
 *
 * What is NOT taken over: the selling paragraphs ("pains", "why us", the short cases). The lead of each page is a plain
 * statement of what is done, in the studio's facts. The site is in Russian only; a few borrowed words in the running text
 * were replaced by Russian ones (AI, event, digital, VFX), package names and the names of platforms and cameras were not.
 * TODO (studio): read the leads once; say if "why us" and the cases should come back.
 */
export interface ProductPackage {
  name: string;
  price: string;
  /** The line under the price. */
  note?: string;
  includes: string[];
  /** The one most often chosen. */
  featured?: boolean;
}

export interface Product {
  /** Two plain sentences under the name. */
  lead: string;
  /** The line next to the starting price. */
  priceNote: string;
  fitFor?: string[];
  deliverables?: string[];
  packages?: ProductPackage[];
  includes?: { group: string; items: string[] }[];
  steps: { title: string; text: string }[];
  timeline?: string[];
  terms?: string[];
  geo?: string;
  /** The phrase the visitor sends to start: it goes into the chat with one click. */
  ask: string;
}

export interface ProductLabels {
  more: string;
  price: string;
  featured: string;
  fitFor: string;
  deliverables: string;
  includes: string;
  steps: string;
  timeline: string;
  terms: string;
  geo: string;
  works: string;
  next: string;
  /** Before the phrase on the button: Написать «ПАКЕТ». */
  write: string;
  /** What happens after the message, for a direction with fixed prices and for one that is estimated. */
  afterFixed: string;
  afterQuote: string;
  nextDirection: string;
  all: string;
}

